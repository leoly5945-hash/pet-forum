function pfTermsLang(lang) {
    document.getElementById('pft-vi').style.display = lang === 'vi' ? '' : 'none';
    document.getElementById('pft-en').style.display = lang === 'en' ? '' : 'none';
    document.querySelectorAll('.pf-terms-lang-switcher a').forEach(function(a, i) {
        a.classList.toggle('active', (lang === 'vi' && i === 0) || (lang === 'en' && i === 2));
    });
    document.cookie = 'pf_lang=' + lang + ';path=/;max-age=2592000';
}
document.addEventListener('DOMContentLoaded', function() {
    var params = new URLSearchParams(window.location.search);
    var lang = params.get('lang') || (document.cookie.match(/pf_lang=([^;]+)/) || [])[1] || 'vi';
    if (lang === 'en') pfTermsLang('en');
});
</script>
